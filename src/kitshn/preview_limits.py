"""Opt-in CPU and memory limits for pull request previews and their image builds.

All limited deployments of one recipe share one systemd slice, so together they stay inside one
budget. Their image builds run in a BuildKit container of the recipe with the same limits. A
deploy without limits, such as every production deploy, uses neither.
"""

from __future__ import annotations

from dataclasses import dataclass
import json
import math
from pathlib import Path
from typing import cast

import yaml

from .errors import KitshnError
from .filesystem import write_if_changed
from .models import Deployment, Recipe
from .runner import CommandRunner

SYSTEMD_DIR = Path("/etc/systemd/system")
MEMORY_UNITS = {"m": 1024**2, "g": 1024**3}
LIMITS_SHAPE = "limits must be a mapping with cpus and memory, such as {cpus: 2, memory: 3g}"
GENERATED_HEADER = "# Generated by KitSHn. Do not edit."


@dataclass(frozen=True, slots=True)
class PreviewLimits:
    """A budget that all limited deployments of one recipe share."""

    cpu_percent: int
    memory: str

    @classmethod
    def parse(cls, cpus: object, memory: object) -> PreviewLimits:
        if isinstance(cpus, bool) or not isinstance(cpus, int | float) or not math.isfinite(cpus):
            msg = f"limits cpus must be a number of CPUs, such as 2 or 1.5, got {cpus!r}"
            raise KitshnError(msg)
        cpu_percent = round(cpus * 100)
        if cpu_percent < 1:
            msg = f"limits cpus must be at least 0.01, got {cpus!r}"
            raise KitshnError(msg)
        size = memory.lower() if isinstance(memory, str) else ""
        amount = size[:-1]
        if size[-1:] not in MEMORY_UNITS or not (amount.isascii() and amount.isdigit()) or int(amount) < 1:
            msg = f"limits memory must be a whole number of megabytes or gigabytes, such as 512m or 3g, got {memory!r}"
            raise KitshnError(msg)
        return cls(cpu_percent=cpu_percent, memory=size)

    @property
    def cpus(self) -> str:
        return f"{self.cpu_percent / 100:g}"

    @property
    def memory_bytes(self) -> int:
        return int(self.memory[:-1]) * MEMORY_UNITS[self.memory[-1]]

    def deploy_flags(self) -> list[str]:
        return ["--limit-cpus", self.cpus, "--limit-memory", self.memory]


def parse_limits(value: object) -> PreviewLimits | None:
    """Validate the `limits` mapping of a `.kitshn.yaml` entry, or of the resolve output."""

    if value is None:
        return None
    if not isinstance(value, dict) or set(value) != {"cpus", "memory"}:
        raise KitshnError(LIMITS_SHAPE)
    fields = cast(dict[str, object], value)
    return PreviewLimits.parse(fields["cpus"], fields["memory"])


def limits_output(limits: PreviewLimits | None) -> str:
    """`limits` as one output line: empty when unset, else a JSON mapping."""

    if limits is None:
        return ""
    return json.dumps({"cpus": float(limits.cpus), "memory": limits.memory})


def parse_limits_output(raw: str) -> PreviewLimits | None:
    if not raw:
        return None
    try:
        return parse_limits(json.loads(raw))
    except json.JSONDecodeError as error:
        msg = f"KITSHN_LIMITS must be a JSON mapping, got {raw!r}"
        raise KitshnError(msg) from error


def preview_slice(recipe: Recipe) -> str:
    """The systemd slice of the recipe's limited deployments, such as kitshn-previews-owner-repo.slice.

    A dash in a slice name starts a child slice. So a dash inside the owner or the repo becomes
    `\\x2d`, as `systemd-escape` does, and every recipe's slice sits under kitshn-previews.slice.
    """

    parts: list[str] = []
    for part in (recipe.owner.lower(), recipe.repo.lower()):
        if not all(char.isascii() and (char.isalnum() or char in "-_.") for char in part):
            msg = f"recipe name has characters that a systemd slice name cannot hold: {recipe.full_name}"
            raise KitshnError(msg)
        parts.append(part.replace("-", "\\x2d"))
    return "kitshn-previews-" + "-".join(parts) + ".slice"


def preview_builder(recipe: Recipe) -> str:
    """The buildx builder of the recipe's limited deployments.

    GitHub owner names have no dot, so the dot after the owner keeps the name unique per recipe.
    """

    return f"kitshn-previews.{recipe.owner.lower()}.{recipe.repo.lower()}"


def slice_unit(recipe: Recipe, limits: PreviewLimits) -> str:
    # Without swap the kernel kills a process in the slice at MemoryMax. MemorySwapMax=0 keeps
    # that true when the host gets swap, so previews never push production out to swap.
    return "\n".join(
        [
            GENERATED_HEADER,
            "[Unit]",
            f"Description=KitSHn previews of {recipe.full_name}",
            "",
            "[Slice]",
            f"CPUQuota={limits.cpu_percent}%",
            f"MemoryMax={limits.memory_bytes}",
            "MemorySwapMax=0",
            "",
        ]
    )


def compose_override(service_names: list[str], slice_name: str) -> str:
    services = {name: {"cgroup_parent": slice_name} for name in service_names}
    return GENERATED_HEADER + "\n" + yaml.safe_dump({"services": services}, sort_keys=True)


def apply_preview_limits(
    deployment: Deployment, service_names: list[str], limits: PreviewLimits, runner: CommandRunner
) -> None:
    """Put the services in the recipe's preview slice and limit the recipe's preview builder.

    The slice unit holds the budget; a deploy that changes it reloads systemd, which applies the
    new values to the running slice. The override file puts the containers in the slice, and its
    presence makes every Compose command of the deployment use it and the builder.
    """

    slice_name = preview_slice(deployment.recipe)
    unit_path = SYSTEMD_DIR / slice_name
    override = compose_override(service_names, slice_name)
    if runner.dry_run:
        print(f"+ write {unit_path}")
        print(f"+ write {deployment.preview_limits_file}")
    else:
        if write_if_changed(unit_path, slice_unit(deployment.recipe, limits)):
            runner.run(["systemctl", "daemon-reload"])
        write_if_changed(deployment.preview_limits_file, override)

    builder = preview_builder(deployment.recipe)
    if runner.run(["docker", "buildx", "inspect", builder], capture=True, check=False).returncode != 0:
        runner.run(["docker", "buildx", "create", "--name", builder, "--driver", "docker-container"])
    runner.run(["docker", "buildx", "inspect", "--bootstrap", builder], capture=True)
    # buildx ignores its cgroup-parent option when Docker uses the systemd cgroup driver, so the
    # builder cannot join the slice. Limit its container instead; build steps run inside it.
    # buildx names that container buildx_buildkit_<builder>0. If buildx renames it, this
    # command fails the deploy, and the name needs an update here.
    memory = str(limits.memory_bytes)
    container = f"buildx_buildkit_{builder}0"
    runner.run(["docker", "update", "--memory", memory, "--memory-swap", memory, "--cpus", limits.cpus, container])
